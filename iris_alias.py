def _w(t):
    return t.lower().replace("ё", "е").strip("?!.,:;…\"'()«»")


def alias(canon, *variants, need_reply=False):
    for v in variants:
        ALIASES[" ".join(_w(x) for x in v.split())] = (canon, need_reply)


