def apply(first, msg=None):
    """Возвращает основную команду для синонима либо исходную строку."""
    if not first:
        return first
    toks = first.split()
    # обращение к боту: «надзор, кто я», «бот кто я»
    while len(toks) > 1 and _w(toks[0]) in _ADDRESS:
        toks = toks[1:]
    while len(toks) > 1 and _w(toks[0]) in _FILLER:
        toks = toks[1:]
    norm = [_w(t) for t in toks]
    for n in range(min(_MAXW, len(toks)), 0, -1):
        key = " ".join(norm[:n])
        hit = ALIASES.get(key)
        if hit:
            canon, need_reply = hit
            if need_reply and not (msg is not None and getattr(msg, "reply_to_message", None)):
                continue
            rest = " ".join(toks[n:])
            # однословный синоним с хвостом — только для команд с аргументами (иначе обычная речь ловилась бы как команда)
            if n == 1 and rest and canon not in _MOD_CANON and not need_reply:
                continue
            if n == 1 and canon == "кубы" and rest and not rest.split()[0].isdigit():
                continue
            return canon + (" " + rest if rest else "")
    if toks:
        toks[-1] = toks[-1].rstrip("?")
    return " ".join(toks)


m.ALIAS_FN = apply
